#!/usr/bin/env python3
"""
gen_ui_assets.py — generate ui_assets.c from the Svelte dist/ output.

Reads each UI file, gzips text assets, and emits a C source file containing:
  - A byte array for each file
  - A ui_files[] routing table (uri → data, size, content-type, gzipped flag)

Usage:
    python3 gen_ui_assets.py <dist_dir> <output_c_file>

Called automatically by the http_server CMakeLists.txt build step.
"""

import sys
import os
import gzip
import struct

DIST_DIR   = sys.argv[1]
OUTPUT     = sys.argv[2]

# Files to embed: (dist-relative path, URL path, content-type, gzip?)
# Icons are already compressed — don't gzip them.
FILES = [
    ("index.html",            "/index.html",            "text/html; charset=utf-8",       True),
    ("assets/index.js",       "/assets/index.js",       "application/javascript",         True),
    ("assets/index.css",      "/assets/index.css",      "text/css",                       True),
    ("manifest.webmanifest",  "/manifest.webmanifest",  "application/manifest+json",      True),
    ("registerSW.js",         "/registerSW.js",         "application/javascript",         True),
    ("sw.js",                 "/sw.js",                 "application/javascript",         True),
    ("icons/icon-192.png",    "/icons/icon-192.png",    "image/png",                      False),
    ("icons/icon-512.png",    "/icons/icon-512.png",    "image/png",                      False),
]

def c_sym(path):
    """Convert a dist-relative path to a valid C identifier."""
    return path.replace("/", "_").replace(".", "_").replace("-", "_")

def to_c_array(data, name):
    lines = [f"static const uint8_t {name}[] = {{"]
    for i in range(0, len(data), 16):
        chunk = data[i:i+16]
        hex_bytes = ", ".join(f"0x{b:02x}" for b in chunk)
        lines.append(f"    {hex_bytes},")
    lines.append("};")
    return "\n".join(lines)

out_lines = [
    "// ui_assets.c — auto-generated by gen_ui_assets.py — do not edit",
    "#include \"ui_assets.h\"",
    "#include <stdint.h>",
    "#include <stddef.h>",
    "",
]

table_entries = []

for rel_path, uri, ctype, do_gzip in FILES:
    full_path = os.path.join(DIST_DIR, rel_path)
    with open(full_path, "rb") as f:
        raw = f.read()

    if do_gzip:
        data = gzip.compress(raw, compresslevel=9)
        gz_flag = "1"
    else:
        data = raw
        gz_flag = "0"

    sym = c_sym(rel_path)
    out_lines.append(to_c_array(data, sym))
    out_lines.append("")
    table_entries.append((uri, sym, len(data), ctype, gz_flag))

# Routing table
out_lines.append("const ui_file_t ui_files[] = {")
for uri, sym, size, ctype, gz in table_entries:
    out_lines.append(f'    {{ "{uri}", {sym}, {size}, "{ctype}", {gz} }},')
# SPA fallback alias: "/" → index.html (duplicate for clarity)
index_sym = c_sym("index.html")
out_lines.append(f'    {{ "/", {index_sym}, {table_entries[0][2]}, "text/html; charset=utf-8", 1 }},')
out_lines.append('    { NULL, NULL, 0, NULL, 0 },')
out_lines.append("};")
out_lines.append("")
out_lines.append(f"const size_t ui_files_count = sizeof(ui_files) / sizeof(ui_files[0]) - 1;")
out_lines.append("")

os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
with open(OUTPUT, "w") as f:
    f.write("\n".join(out_lines))

# Also emit the header alongside the source so #include "ui_assets.h" resolves
# from the same directory (which is already in INCLUDE_DIRS).
header_path = os.path.join(os.path.dirname(OUTPUT), "ui_assets.h")
header = """\
#pragma once
#include <stdint.h>
#include <stddef.h>

typedef struct {
    const char    *uri;
    const uint8_t *data;
    size_t         size;
    const char    *content_type;
    int            gzipped;
} ui_file_t;

extern const ui_file_t ui_files[];
extern const size_t    ui_files_count;
"""
with open(header_path, "w") as f:
    f.write(header)

print(f"gen_ui_assets: wrote {OUTPUT} ({len(table_entries)} files)")
